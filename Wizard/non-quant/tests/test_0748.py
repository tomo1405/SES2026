python
import re
import math
import pytest

def task_func(s):
    numbers = re.findall(r'\b\d+(?:\.\d+)?\b', s)  # Use non-capturing group for decimals
    count = len(numbers)
    sqrt_sum = sum(math.sqrt(float(num)) for num in numbers if num)  # Ensure conversion to float
    return count, sqrt_sum

def test_task_func():
    assert task_func('123 456.789') == (2, 5.8660254037844386)
    assert task_func('123.456 789') == (2, 5.8660254037844386)
    assert task_func('123 456.789 0.000') == (3, 5.8660254037844386)
    assert task_func('123.456 789 0.000') == (3, 5.8660254037844386)
    assert task_func('123 456.789 0.000 123.456') == (4, 7.866025403784438)
    assert task_func('123.456 789 0.000 123.456') == (4, 7.866025403784438)
    assert task_func('123 456.789 0.000 123.456 0.000') == (5, 7.866025403784438)
    assert task_func('123.456 789 0.000 123.456 0.000') == (5, 7.866025403784438)
    assert task_func('123 456.789 0.000 123.456 0.000 123.456') == (6, 9.866025403784438)
    assert task_func('123.456 789 0.000 123.456 0.000 123.456') == (6, 9.866025403784438)
    assert task_func('123 456.789 0.000 123.456 0.000 123.456 0.000') == (7, 9.866025403784438)
    assert task_func('123.456 789 0.000 123.456 0.000 123.456 0.000') == (7, 9.866025403784438)
    assert task_func('123 456.789 0.000 123.456 0.000 123.456 0.000 123.456') == (8, 11.866025403784438)
    assert task_func('123.456 789 0.000 123.456 0.000 123.456 0.000 123.456') == (8, 11.866025403784438)
    assert task_func('123 456.789 0.000 123.456 0.000 123.456 0.000 123.456 0.000') == (9, 11.866025403784438)
    assert task_func('123.456 789 0.000 123.456 0.000 123.456 0.000 123.456 0.000') == (9, 11.866025403784438)
    assert task_func('123 456.789 0.000 123.456 0.000 123.456 0.000 123.456 0.000 123.456') == (10, 13.866025403784438)
    assert task_func('123.456 789 0.000 123.456 0.000 123.456 0.000 123.456 0.000 123.456') == (10, 13.866025403784438)